"""Deterministic local mock provider; this is not genuine AI analysis."""

from app.models.ai_analysis import AIAnalysis
from app.models.risk_assessment import RiskAssessment
from app.models.security_event import SecurityEventRecord


class MockAIAnalysisProvider:
    """Generate predictable explanatory output without external API calls."""

    def analyze(
        self,
        event: SecurityEventRecord,
        risk_assessment: RiskAssessment,
    ) -> AIAnalysis:
        event_data = event.event.model_dump(mode="json")
        resource_data = event_data.get("resource") or {}

        event_type = event_data.get("event_type", "unknown")
        severity = event_data.get("severity", "unknown")
        description = event_data.get("description") or "No description provided."
        resource_name = (
            resource_data.get("display_name")
            or resource_data.get("resource_id")
            or "Unspecified resource"
        )

        observations = [
            f"Event source: {event_data.get('source', 'unknown')}.",
            f"Event type: {event_type}.",
            f"Reported severity: {severity}.",
            f"Resource: {resource_name}.",
        ]

        if resource_data.get("internet_exposed") is True:
            observations.append("The affected resource is marked as internet-exposed.")

        factor_summary = [
            f"{factor.name} (+{factor.points}): {factor.explanation}"
            for factor in risk_assessment.factors
        ]

        return AIAnalysis(
            event_id=str(risk_assessment.event_id),
            provider="mock",
            summary=(
                f"Mock analysis of a {severity} {event_type} event. "
                f"The deterministic risk engine assigned "
                f"{risk_assessment.risk_level.value} risk "
                f"with a score of {risk_assessment.risk_score}/100."
            ),
            threat_explanation=(
                f"The event describes: {description} "
                "This local mock provider does not independently verify "
                "threat intelligence or exploit activity."
            ),
            potential_impact=(
                f"The affected resource is {resource_name}. "
                f"The current deterministic assessment is "
                f"{risk_assessment.risk_level.value} "
                f"({risk_assessment.risk_score}/100). "
                "Actual impact requires investigation and validation."
            ),
            key_observations=observations + factor_summary,
            recommended_actions=risk_assessment.recommendations,
            investigation_steps=[
                "Validate the event against the originating security source.",
                "Confirm the affected resource and its business owner.",
                "Review relevant logs and activity around the event timestamp.",
                "Verify whether the reported exposure or exploitation conditions are present.",
            ],
            limitations=[
                "This result was generated by a deterministic local mock provider.",
                "No external AI model or threat-intelligence service was called.",
                "Findings are explanatory and must be validated by a security analyst.",
                "The deterministic risk assessment remains the authoritative risk score.",
            ],
        )
